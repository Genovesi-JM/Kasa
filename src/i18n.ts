const savedLanguage =
  typeof window === "undefined"
    ? "pt"
    : window.localStorage.getItem("kasa-language");
const initialLanguage = languages.some(({ code }) => code === savedLanguage)
  ? (savedLanguage as LanguageCode)
  : "pt";

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: en },
    pt: { translation: pt },
    es: { translation: esComplete },
    fr: { translation: frComplete },
    ar: { translation: arComplete },
    zh: { translation: zhComplete },
  },
  lng: initialLanguage,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export function displayTranslation(
  value: string,
  english: string,
  language = i18n.resolvedLanguage,
): string {
  return (language === "ar" || language === "zh") && value !== english
    ? `${value} (${english})`
    : value;
}

export async function setLanguage(language: LanguageCode) {
  await i18n.changeLanguage(language);
  window.localStorage.setItem("kasa-language", language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
}

document.documentElement.lang = initialLanguage;
document.documentElement.dir = initialLanguage === "ar" ? "rtl" : "ltr";

